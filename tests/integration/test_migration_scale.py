pytestmark = [pytest.mark.integration, pytest.mark.stress, pytest.mark.slow]

# Each owner has 20 MiB of weights and 28 observed scalar fields.
FULL_OWNERS = 2304
SHAPE = (5120, 1024)
CHUNK = (1024, 1024)
ROOT = Path(__file__).resolve().parents[2]


def _fixture(directory, owners):
    import h5py

    directory.mkdir()
    index = directory / "metadata_index.db"
    with closing(sqlite3.connect(index)) as db, db:
        db.execute(
            "CREATE TABLE parameters(uid TEXT PRIMARY KEY, name TEXT, model_id TEXT, "
            "ptype TEXT, json_data TEXT)"
        )
        db.execute(
            "CREATE TABLE aggregates(uid TEXT PRIMARY KEY, field_name TEXT, "
            "context_models TEXT, context_params TEXT, json_data TEXT)"
        )
        db.executemany(
            "INSERT INTO parameters VALUES(?,?, 'net', 'DENSE', '{}')",
            ((str(i), f"layer.{i}.weight") for i in range(owners)),
        )
    light = directory / "sqlite_storage.db"
    with closing(SQLiteStorageManager(str(light))) as manager:
        manager.connect()
    names = ["weights", *(f"metric{i}" for i in range(28))]
    with closing(sqlite3.connect(light)) as db, db:
        db.executemany(
            "INSERT INTO field_registry VALUES('parameters',?)", ((n,) for n in names)
        )
        db.executemany(
            "INSERT INTO storage(table_name,field,obj_uid,value_type,value_data) "
            "VALUES('parameters',?,?,'json',?)",
            (
                (name, str(i), b'"__HEAVY__"' if name == "weights" else str(i).encode())
                for i in range(owners)
                for name in names
            ),
        )
    block = np.broadcast_to(np.arange(CHUNK[1], dtype="<f4"), CHUNK)
    compressor = zlib.compressobj()
    prefix = compressor.compress(block.tobytes()[:-4])
    expected = {}
    metadata = json.dumps({"shape": list(SHAPE), "dtype": "float32"})
    with h5py.File(directory / "hdf5_storage.h5", "w") as hdf:
        group = hdf.create_group("root/parameters/weights")
        for i in range(owners):
            dataset = group.create_dataset(
                str(i), SHAPE, dtype="<f4", chunks=CHUNK, compression="gzip"
            )
            dataset.attrs["type"] = "ndarray"
            dataset.attrs["value_meta"] = metadata
            for offset in range(0, SHAPE[0], CHUNK[0]):
                chunk = compressor.copy()
                stamp = i * (SHAPE[0] // CHUNK[0]) + offset // CHUNK[0]
                compressed = (
                    prefix + chunk.compress(struct.pack("<f", stamp)) + chunk.flush()
                )
                dataset.id.write_direct_chunk((offset, 0), compressed)
                expected[i, offset] = hashlib.sha256(compressed).digest()
            assert dataset.id.get_num_chunks() == SHAPE[0] // CHUNK[0]
    return expected


def _measure(directory):
    import h5py
    from scripts.bench_pipeline import _PeakRSS

    def guard(original):
        def read(dataset, *args, **kwargs):
            parts = dataset.name.split("/")
            if "weights" in (parts[-1], parts[-2]):
                raise AssertionError(f"Migration read weight values at {dataset.name}")
            return original(dataset, *args, **kwargs)

        return read

    with ExitStack() as stack:
        for method in ("__getitem__", "__array__", "read_direct"):
            original = getattr(h5py.Dataset, method)
            stack.enter_context(patch.object(h5py.Dataset, method, guard(original)))
        memory = stack.enter_context(_PeakRSS())
        start = time.monotonic()
        # The input is generated by this test and can be regenerated exactly.
        report = migrate_store(
            directory, backup_dir=directory.parent / (directory.name + "-backup")
        )
        elapsed = time.monotonic() - start
    measurements = {
        "values": report["values"],
        "seconds": elapsed,
        "transform_seconds": report["transform_seconds"],
        "peak_bytes": memory.peak_bytes,
        "rss_method": memory.method,
    }
    (directory / "measurement.json").write_text(json.dumps(measurements))


def test_migration_scales_with_catalog_size_and_keeps_weight_arrays_out_of_memory(
    tmp_path,
):
    import h5py

    measurements = []
    for n in (FULL_OWNERS // 2, FULL_OWNERS):
        directory = tmp_path / str(n)
        expected = _fixture(directory, n)
        subprocess.run(  # noqa: S603 - run this module with the active interpreter
            [sys.executable, __file__, str(directory)],
            check=True,
            env={
                **os.environ,
                "PYTHONPATH": os.pathsep.join((str(ROOT / "src"), str(ROOT))),
            },
        )
        report = json.loads((directory / "measurement.json").read_text())
        logical_size = n * int(np.prod(SHAPE)) * 4
        assert report["values"] == n * 29
        assert 0 < report["peak_bytes"] < logical_size // 10
        assert report["transform_seconds"] > 0
        with closing(sqlite3.connect(directory / "metadata_index.db")) as index:
            (total,) = index.execute(
                "SELECT sum(size_bytes) FROM live_field_values WHERE field='weights'"
            ).fetchone()
            assert total == logical_size
            keys = index.execute(
                "SELECT p.name,v.storage_key FROM live_field_values v "
                "JOIN parameters p ON p.uid=v.obj_uid WHERE v.field='weights'"
            )
            with h5py.File(directory / "hdf5_storage.h5") as hdf:
                for name, key in keys:
                    owner = int(name.split(".")[1])
                    value = hdf["root/" + key]
                    assert value.id.get_num_chunks() == SHAPE[0] // CHUNK[0]
                    assert value.shape == SHAPE
                    assert value.dtype == np.dtype("<f4")
                    for offset in range(0, SHAPE[0], CHUNK[0]):
                        mask, payload = value.id.read_direct_chunk((offset, 0))
                        assert mask == 0
                        assert hashlib.sha256(payload).digest() == expected.pop(
                            (owner, offset)
                        )
            assert not expected
        measurements.append(report)
        logging.getLogger(__name__).info(
            "Migration measurements %s",
            {"owners": n, "logical_value_bytes": logical_size, **report},
        )
    half, full = measurements
    assert full["transform_seconds"] < 3.5 * half["transform_seconds"]


if __name__ == "__main__":
    _measure(Path(sys.argv[1]))
